/**
 * Единственное, что кнопка-триггер и всплывающий список обязаны считать
 * одинаково, — id пункта.
 *
 * Кнопка объявляет активный пункт через aria-activedescendant, то есть ссылается
 * на id, который проставляет себе сам <li> в VelSelectList.vue. Собери эту
 * строку в двух шаблонах — и однажды они разъедутся: ссылка укажет в пустоту,
 * а скринридер перестанет называть пункт, по которому идут стрелками. Поэтому
 * правило живёт в одном файле, а не повторяется в разметке.
 */
export function selectOptionId(triggerId: string, index: number): string {
  return `${triggerId}-option-${index}`
}
