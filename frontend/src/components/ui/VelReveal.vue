<script setup lang="ts">
import { computed, onMounted, ref } from 'vue'
import { gsap } from 'gsap'
import { useEventListener } from '@vueuse/core'
import { useGsapContext } from '@/composables/useGsapContext'
import {
  REVEAL_ATTR,
  REVEAL_DELAY_ATTR,
  REVEAL_MOTION_OK,
  REVEAL_TILT_ATTR,
  revealNow,
  singleReveal,
  useRevealStage,
} from '@/composables/useRevealStage'

/**
 * Обёртка появления: пока блок вне кадра — он прозрачен и сдвинут вниз,
 * при попадании в кадр проявляется.
 *
 * Движок теперь GSAP + ScrollTrigger, но публичный набор пропов прежний:
 * компонент зовут восемь секций лендинга, и переписывать их разметку
 * ради смены движка незачем.
 *
 * КТО ИМЕННО АНИМИРУЕТ. Внутри @/components/ui/VelStage.vue — сцена: она
 * собирает все помеченные блоки секции и показывает их одной пачкой со stagger,
 * потому что отставание заголовка от карточек обязано считаться одним твином,
 * а не задержками, расставленными руками. Вне сцены блок обслуживает себя сам,
 * теми же цифрами из @/composables/useRevealStage.ts. Ровно один из двух
 * путей отработает: сцена объявляет себя в setup, то есть раньше детей.
 *
 * Тег корня задаётся через `as`, потому что обёртка обязана оставаться
 * законным ребёнком родителя: <div> внутри <ul> сломал бы список, а лишний
 * контейнер внутри grid забрал бы себе ячейку и развалил бы равные высоты
 * карточек. Своих отступов компонент не задаёт — классы приходят снаружи
 * и попадают на корень через fallthrough.
 */
interface Props {
  /** Задержка перед проявлением: сверх лесенки, которую даёт сцена */
  delayMs?: number
  /** Тег корня: li, h2, p, a — что требует окружающая разметка */
  as?: string
  /** Видно с первого кадра, без анимации и без ожидания скролла — первый экран */
  immediate?: boolean
  /**
   * Появляться с наклоном: блок лежит градусов на шесть и выпрямляется вместе
   * с подъёмом. Нужен для плиток, стоящих сеткой, — наклон читается как глубина.
   *
   * ОБЯЗАТЕЛЬНОЕ УСЛОВИЕ: на родителе (том, что держит сетку) должен стоять
   * класс .vel-depth — перспектива берётся оттуда. Без неё поворот вокруг
   * горизонтальной оси схлопывается в вертикальное сжатие и выглядит поломкой,
   * а не глубиной.
   */
  tilt?: boolean
}

const props = withDefaults(defineProps<Props>(), {
  delayMs: 0,
  as: 'div',
  immediate: false,
  tilt: false,
})

/** Появлением этого блока уже занимается сцена секции? */
const inStage = useRevealStage()

/*
 * Прячет блок только класс ожидания, и ставит его сам компонент. Значит,
 * скрытым контент бывает ровно тогда, когда скрипт жив: не отработал бандл —
 * на странице нет ни класса, ни этих элементов, и текст остаётся читаемым.
 * Правила `opacity: 0` в таблице стилей по умолчанию нет ни для кого.
 *
 * Класс держит первый кадр — от разметки до момента, когда до элемента
 * доберётся GSAP. Дальше состояние ведут инлайновые стили твина, и класс
 * снимается: иначе он остался бы висеть вторым, никем не управляемым
 * источником прозрачности.
 */
const waiting = ref(!props.immediate)

/**
 * Метка для сцены и собственная задержка блока. Отдельными строками в шаблоне
 * их не пишем: имена атрибутов заданы в одном месте — там же, где селектор,
 * которым сцена их ищет.
 */
const markerAttrs = computed<Record<string, string>>(() => {
  // immediate не участвует в очереди: сцена его не видит и не трогает
  if (props.immediate) return {}

  const attrs: Record<string, string> = { [REVEAL_ATTR]: '' }
  const delay = Number.isFinite(props.delayMs) && props.delayMs > 0 ? Math.round(props.delayMs) : 0
  if (delay > 0) attrs[REVEAL_DELAY_ATTR] = String(delay)
  // Метка, а не проп внутрь: и сцена, и одиночный путь читают наклон с самого
  // элемента — так обе ветки берут его из одного места.
  if (props.tilt) attrs[REVEAL_TILT_ATTR] = ''
  return attrs
})

const root = useGsapContext(() => {
  const element = root.value
  if (!element) return

  // Внутри сцены собственный ScrollTrigger был бы вторым твином на тот же
  // элемент: два движения на одну прозрачность дают дрожание, а не появление.
  if (props.immediate || inStage) return

  /*
   * prefers-reduced-motion — штатным механизмом GSAP. Внутри условия создаётся
   * и скрытое состояние, и ScrollTrigger: при 'reduce' не создаётся ничего,
   * блок просто виден. Смену настройки на ходу matchMedia отследит сам.
   * Уборка не нужна: matchMedia создан внутри gsap.context и уедет по revert().
   */
  gsap.matchMedia().add(REVEAL_MOTION_OK, () => {
    singleReveal(element, props.delayMs)
  })
})

/*
 * Снятие класса ожидания намеренно отдельным хуком, а не строкой внутри
 * контекста: контекст не создаётся, если ref не привязался к элементу, и тогда
 * класс остался бы висеть — блок исчез бы навсегда из-за причины, к анимации
 * отношения не имеющей. Здесь же он снимается при любом исходе.
 *
 * Порядок соблюдён: useGsapContext регистрирует свой onMounted раньше, значит
 * скрытое состояние GSAP успевает встать до того, как класс уйдёт. Vue и вовсе
 * применит снятие следующей микрозадачей — кадра между ними не будет.
 */
onMounted(() => {
  waiting.value = false
})

/*
 * Фокус важнее очереди: клавиатура может увести в блок, который ещё не
 * проявился, и тогда пользователь целится в невидимое. Слушатель нужен только
 * вне сцены: внутри неё focusin всплывает до её корня, и второй обработчик на
 * том же событии показывал бы блок дважды.
 */
if (!inStage && !props.immediate) {
  useEventListener(root, 'focusin', () => {
    const element = root.value
    if (element) revealNow(element)
  })
}
</script>

<template>
  <component :is="as" ref="root" v-bind="markerAttrs" :class="waiting ? 'vel-reveal--wait' : ''">
    <slot />
  </component>
</template>

<style scoped>
/* Единственное место, где контент невидим. Класс приходит из скрипта —
   см. комментарий у waiting. Глобальный селектор здесь недопустим:
   scoped-компилятор режет потомка у :global(), а класс .vel-reveal занят
   ещё и в @/components/magic/VelRevealList.vue. */
.vel-reveal--wait {
  opacity: 0;
}

@media print {
  /*
    На печати важнее содержимое, а не очередь появления. Здесь !important
    оправдан: состояние ожидания к этому моменту ведут инлайновые стили GSAP,
    а перебить инлайн таблица стилей больше ничем не может.
  */
  .vel-reveal--wait,
  [data-vel-reveal] {
    opacity: 1 !important;
    visibility: visible !important;
    transform: none !important;
  }
}
</style>
