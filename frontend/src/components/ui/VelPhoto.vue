<script setup lang="ts">
import { computed, onMounted, onUnmounted, ref } from 'vue'
import { gsap } from 'gsap'
import { cn } from '@/lib/cn'
import { useControlAttrs } from '@/composables/useControlAttrs'

/**
 * Фотография в оформлении Velora.
 *
 * Рамки и подложки нет намеренно: у снимков светлый фон, и в прямоугольной
 * рамке они читались бы как вставленные картинки. Вместо рамки края растворены
 * маской, а сверху лежит слабый синий налёт — он сводит разнородные фотографии
 * к гамме сайта. Прозрачного PNG для этого не требуется.
 *
 * Ширина и высота обязательны: без них браузер не знает пропорцию до загрузки
 * и страница дёргается, когда картинка приезжает.
 *
 * При скролле снимок едет внутри своей рамки — лёгкий параллакс, который
 * отделяет фотографию от текста рядом. Ход намеренно крошечный: это акцент,
 * а не аттракцион на кредитном сайте.
 */
interface Props {
  src: string
  /** Осмысленное описание. Пустая строка = декоративное фото. */
  alt: string
  width: number
  height: number
  /** Фото на первом экране грузим сразу, остальные — лениво. */
  eager?: boolean
  /**
   * С какой стороны снимок заходит на соседнюю колонку.
   * 'start' — налево (фото стоит справа от текста), 'end' — направо.
   * Логические стороны, а не left/right: при зеркальной раскладке
   * заход останется со стороны текста, а не уедет за экран.
   */
  bleed?: 'start' | 'end' | 'none'
  /**
   * Снимок с собственной альфой — предмет уже вырезан, фона у файла нет.
   * Тогда оформление кадра (маска краёв и размытая подложка) не применяется:
   * разбор в .vel-photo--cutout ниже.
   */
  cutout?: boolean
}

const props = withDefaults(defineProps<Props>(), {
  eager: false,
  bleed: 'none',
  cutout: false,
})

const BLEED_CLASS: Record<NonNullable<Props['bleed']>, string> = {
  start: 'vel-photo--bleed-start',
  end: 'vel-photo--bleed-end',
  none: '',
}

defineOptions({ inheritAttrs: false })

const { externalClass, passThrough } = useControlAttrs()

const figureClass = computed(() =>
  cn(
    'vel-photo',
    BLEED_CLASS[props.bleed],
    props.cutout && 'vel-photo--cutout',
    externalClass.value,
  ),
)

/** Ход параллакса в процентах высоты кадра: от -6 вверху до +6 внизу экрана. */
const SHIFT_PERCENT = 6
/**
 * Запас, на который картинка крупнее своей рамки.
 * Увеличение раздвигает её на (scale − 1) / 2 в каждую сторону, а сдвиг
 * съедает 6% — значит нужно больше 1.12, иначе на краю хода из-под снимка
 * покажется фон. 1.15 оставляет 1.5% на округления субпиксельной раскладки.
 */
const COVER_SCALE = 1.15

const root = ref<HTMLElement | null>(null)
let ctx: gsap.Context | undefined

onMounted(() => {
  const element = root.value
  if (!element) return

  /*
   * У ВЫРЕЗАННОГО ПРЕДМЕТА ПАРАЛЛАКСА НЕТ, и это исправление, а не экономия.
   *
   * Параллакс возит картинку внутри рамки, поэтому берёт её с запасом:
   * COVER_SCALE увеличивает снимок на 15%, а рамка режет вылет по overflow.
   * Для репортажного кадра это незаметно — подрезается фон по краям. Для
   * вырезанного телефона подрезается САМ ТЕЛЕФОН: замер на 375px давал
   * картинку 368px в рамке 320px, то есть корпус выходил за неё на 48px и
   * терял низ и края. На узком экране это было особенно заметно — рамка там
   * упирается в ширину колонки, и запасу деваться некуда.
   *
   * Возить предмет вокруг его же силуэта незачем: параллакс отделяет
   * фотографию от текста рядом, а вырезанный предмет и без того лежит прямо
   * на фоне страницы.
   */
  if (props.cutout) return

  /* Контекст со ссылкой на <figure> вторым аргументом: селектор внутри ищется
     только среди её потомков, поэтому фото соседних секций не подхватываются. */
  ctx = gsap.context(() => {
    /* Штатный механизм GSAP под prefers-reduced-motion. Ручной проверки здесь
       нет намеренно: matchMedia сам откатывает и увеличение, и сдвиг, если
       пользователь переключит настройку на лету. */
    const media = gsap.matchMedia()

    media.add('(prefers-reduced-motion: no-preference)', () => {
      // Запас ставит сама анимация: без движения незачем и подрезать кадр,
      // а ctx.revert() снимет увеличение вместе с параллаксом.
      gsap.set('.vel-photo__img', { scale: COVER_SCALE })

      gsap.fromTo(
        '.vel-photo__img',
        { yPercent: -SHIFT_PERCENT },
        {
          yPercent: SHIFT_PERCENT,
          // scrub привязывает прогресс к скроллу, поэтому любое смягчение
          // рассинхронизировало бы картинку с колесом.
          ease: 'none',
          scrollTrigger: {
            trigger: element,
            start: 'top bottom',
            end: 'bottom top',
            scrub: true,
          },
        },
      )
    })
  }, element)
})

// Без revert() твин и его ScrollTrigger остались бы жить на отсоединённом узле.
onUnmounted(() => ctx?.revert())
</script>

<template>
  <figure ref="root" v-bind="passThrough" :class="figureClass">
    <!--
      Размытая копия лежит под резкой. Тот же src — браузер берёт его из кэша,
      второго запроса в сеть нет. Для доступности её не существует: alt пустой
      и aria-hidden, иначе скринридер прочитал бы одно фото дважды.
    -->
    <img
      v-if="props.bleed !== 'none' && !props.cutout"
      class="vel-photo__img vel-photo__img--soft"
      :src="props.src"
      alt=""
      aria-hidden="true"
      :width="props.width"
      :height="props.height"
      loading="lazy"
      decoding="async"
    />

    <img
      class="vel-photo__img vel-photo__img--sharp"
      :src="props.src"
      :alt="props.alt"
      :width="props.width"
      :height="props.height"
      :loading="props.eager ? 'eager' : 'lazy'"
      :fetchpriority="props.eager ? 'high' : 'auto'"
      decoding="async"
    />
  </figure>
</template>

<style scoped>
.vel-photo {
  position: relative;
  margin: 0;
  /* Рамка обязана резать вылет параллакса: снимок внутри крупнее её и ездит
     по вертикали. Без клипа он вылезал бы на текст, а маска — у неё по
     умолчанию mask-repeat: repeat — размножилась бы на выехавших краях. */
  overflow: hidden;
  /* Края растворяются, поэтому снимок не обрывается прямоугольником:
     маска мягче любой рамки и не спорит с острой геометрией остального. */
  /* black здесь не цвет из палитры, а трафарет: маску читают по альфе,
     и непрозрачная часть обязана быть полностью непрозрачной. Тот же приём
     и то же обоснование, что в @/components/magic/VelBorderBeam.vue. */
  mask-image: radial-gradient(125% 115% at 50% 42%, black 52%, transparent 100%);
}

/*
  СНИМОК С СОБСТВЕННОЙ АЛЬФОЙ (вырезанный предмет).

  Оформление кадра здесь ОТКЛЮЧЕНО ЦЕЛИКОМ, и это не экономия, а исправление.

  Оба приёма компонента — растворённый край и размытая копия под резкой —
  рассчитаны на прямоугольный кадр: они прячут его границу. У вырезанного
  предмета границы кадра нет вовсе, зато есть силуэт, и оба приёма начинают
  работать против него:

  · МАСКА гасит не край кадра, а сам предмет — у телефона таяли угол корпуса
    и низ экрана, ровно там, где эллипс сходит на нет;
  · РАЗМЫТАЯ КОПИЯ, лежащая под резкой тем же файлом, вылезает из-под силуэта
    расплывшимся серым ореолом. Именно её видно вокруг телефона на белой
    секции — не «фон снимка», а собственную подложку компонента. Файл
    app-accesso.webp уже вырезан: 56.2% его пикселей имеют альфу 0, и вся
    рамка прозрачная.

  Тень предмету не нужна: она нарисована в самом файле.
*/
.vel-photo--cutout {
  mask-image: none;
  /*
    Обрезка тоже снимается. Она нужна была ради параллакса — он возит снимок
    внутри рамки, и без клипа вылет ложился бы на текст. Параллакса у
    вырезанного предмета нет (см. ранний возврат в скрипте), а с обрезкой
    силуэт рисковал бы поймать край рамки на округлении раскладки.
  */
  overflow: visible;
}

.vel-photo__img {
  display: block;
  width: 100%;
  height: auto;
  /* Снимки сгенерированы разными прогонами и различаются по теплоте.
     Лёгкая коррекция сводит их к общему холодному тону сайта. */
  filter: saturate(0.92) contrast(1.02);
}

/*
  ЗАХОД НА СОСЕДНЮЮ КОЛОНКУ.

  Снимок вылезает за свою ячейку отрицательным полем и ложится на фон
  текстовой колонки — но НЕ на сам текст: текст в секции поднят выше
  по слою. Из-за этого фотография перестаёт выглядеть приклеенной
  плиткой и начинает жить в одном пространстве с набором.

  Величина захода растёт вместе с экраном: на телефоне колонки идут
  одна под другой, и залезать там некуда и незачем.
*/
.vel-photo--bleed-start,
.vel-photo--bleed-end {
  --vel-photo-bleed: 0px;
  z-index: 0;
}

/*
  Заход чуть больше зазора между колонками (у секций gap-16, то есть 64px):
  снимок проходит зазор насквозь и заезжает на край текстовой колонки.
  Попадает он при этом на ФОН, а не на буквы — строки в этих колонках
  ограничены по ширине (vel-measure, max-w-prose), и справа от набора
  остаётся пустое поле.

  Страховка на случай длинной строки — в @layer components глобальных
  стилей: соседи по сетке подняты над снимком, поэтому даже при столкновении
  текст остаётся сверху и читаемым.
*/
@media (min-width: 64rem) {
  .vel-photo--bleed-start,
  .vel-photo--bleed-end {
    --vel-photo-bleed: clamp(1.5rem, 5.5vw, 5rem);
  }
}

.vel-photo--bleed-start {
  margin-inline-start: calc(-1 * var(--vel-photo-bleed));
}

.vel-photo--bleed-end {
  margin-inline-end: calc(-1 * var(--vel-photo-bleed));
}

/*
  Размытая копия под резкой. Резкая на стороне захода сходит на нет
  собственной маской, и там наружу выходит размытая — край не обрывается
  линией, а расплывается в фон соседней колонки.

  Именно вторая картинка, а не filter на одном элементе: размыть можно
  только элемент целиком, а нам нужна резкость в теле снимка и мягкость
  ровно на кромке.
*/
.vel-photo__img--soft {
  position: absolute;
  inset: 0;
  height: 100%;
  object-fit: cover;
  filter: blur(18px) saturate(0.9);
  /* Кадр чуть крупнее рамки: иначе размытие оголило бы её край,
     который тут же срезала бы overflow. */
  scale: 1.08;
  opacity: 0.75;
}

.vel-photo--bleed-start .vel-photo__img--sharp {
  mask-image: linear-gradient(to right, transparent 0%, black 26%, black 100%);
}

.vel-photo--bleed-end .vel-photo__img--sharp {
  mask-image: linear-gradient(to left, transparent 0%, black 26%, black 100%);
}

/* Резкая копия обязана лежать выше размытой */
.vel-photo__img--sharp {
  position: relative;
  z-index: 1;
}

/*
  Синий налёт поверх фотографии. multiply, а не обычная заливка: он
  затемняет только средние тона и не выбеливает светлые участки,
  поэтому лица остаются живыми, а фон уходит в гамму сайта.
*/
.vel-photo::after {
  content: '';
  position: absolute;
  inset: 0;
  background-color: var(--color-accent);
  opacity: 0.1;
  mix-blend-mode: multiply;
  pointer-events: none;
}

/*
  У ВЫРЕЗАННОГО ПРЕДМЕТА НАЛЁТА НЕТ — И ЭТО ГЛАВНАЯ ПРИЧИНА, ПО КОТОРОЙ ФОН
  ВОКРУГ ТЕЛЕФОНА ОСТАВАЛСЯ ЗАЛИТЫМ.

  Налёт — это ПРЯМОУГОЛЬНИК во всю рамку (inset: 0), а не покраска пикселей
  снимка. Для репортажного кадра разницы нет: кадр сам прямоугольный и занимает
  рамку целиком. У вырезанного предмета рамка занята силуэтом лишь частично, и
  налёт красил всё остальное — то есть ровно те места, которые обязаны были
  остаться пустыми. Снимок с честной альфой при этом выглядел как телефон на
  синей плашке, и никакая правка самого файла этого не убирала.

  Заодно снимаем цветокоррекцию: она сводила разнородные кадры к общей гамме
  сайта, а вырезанный предмет обязан выглядеть собой — подгонять по цвету
  тут нечего и не к чему.
*/
.vel-photo--cutout::after {
  content: none;
}

.vel-photo--cutout .vel-photo__img {
  filter: none;
}
</style>
