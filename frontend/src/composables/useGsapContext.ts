import { onMounted, onUnmounted, ref } from 'vue'
import type { Ref } from 'vue'
import { gsap } from 'gsap'

/**
 * Единственный вход в GSAP из компонентов.
 *
 * Снимает три обязанности, которые иначе повторяются в каждом файле и из
 * которых достаточно забыть одну, чтобы получить утечку:
 *
 * 1. Анимации создаются в onMounted — раньше корневого элемента в DOM нет,
 *    и селектор внутри контекста нашёл бы пустоту.
 * 2. Всё оборачивается в gsap.context(setup, root). Второй аргумент — не
 *    украшение: без него `ctx.selector('.card')` (и любой селектор внутри
 *    контекста) ищет по всему документу и ловит карточки соседних секций.
 * 3. onUnmounted зовёт ctx.revert(). Без него твины и ScrollTrigger остаются
 *    жить на отсоединённых узлах: слушатели скролла продолжают считать
 *    позиции элементов, которых уже нет на странице.
 *
 * Контекст откатывает и вложенные gsap.matchMedia(): при создании внутри
 * контекста matchMedia попадает в его data и получает revert вместе с ним.
 * Поэтому обработку prefers-reduced-motion можно спокойно писать внутри
 * setup — отдельной уборки она не потребует.
 *
 * КОРЕНЬ МОЖНО ПЕРЕДАТЬ СВОЙ. По умолчанию композабл заводит ref сам, и
 * компонент вешает его в шаблоне — так устроено большинство мест. Но когда
 * движение вынесено в отдельный композабл, корнем владеет сам
 * компонент: он объявляет ref и передаёт его дальше. Без этого параметра
 * пришлось бы возвращать ref через два слоя, и в компоненте он оказывался бы
 * объявлен, но нигде не прочитан, — на что справедливо ругается проверка
 * неиспользуемых переменных.
 *
 * @param setup вызывается один раз после монтирования; получает сам контекст
 * @param scope готовый ref под корень; не передан — композабл заведёт свой
 * @returns ref под корень компонента — вешается через `ref="…"` в шаблоне
 */
export function useGsapContext(
  setup: (ctx: gsap.Context) => void,
  scope?: Ref<HTMLElement | null>,
): Ref<HTMLElement | null> {
  const root = scope ?? ref<HTMLElement | null>(null)
  let ctx: gsap.Context | null = null

  onMounted(() => {
    const element = root.value
    // Корня нет — значит ref не привязан к элементу шаблона. Создавать контекст
    // без области видимости нельзя: он молча стал бы глобальным.
    if (!element) return
    ctx = gsap.context(setup, element)
  })

  onUnmounted(() => {
    ctx?.revert()
    ctx = null
  })

  return root
}
