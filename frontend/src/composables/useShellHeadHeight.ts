import { useResizeObserver } from '@vueuse/core'
import type { Ref } from 'vue'

/**
 * Две высоты залипающей шапки кабинета — переменными на корне оболочки.
 *
 * --vel-shell-head-h    ТЕКУЩАЯ высота: от неё залипают меню слева и колонка
 *                       обзора на Home. Меняется вместе со сжатием шапки.
 * --vel-shell-head-full ВЫСОТА В РАЗЖАТОМ ВИДЕ: её резервирует под шапкой
 *                       распорка, чтобы сжатие не меняло высоту документа.
 *
 * ЗАЧЕМ ВТОРАЯ. Шапка сжимается при прокрутке со 152px до 57. Пока она стояла
 * в потоке, это схлопывание уменьшало высоту документа, и браузер СОБСТВЕННЫМ
 * механизмом привязки прокрутки (scroll anchoring) подтягивал позицию на те же
 * 95px, чтобы содержимое не прыгнуло. Позиция уезжала ниже порога разжатия,
 * шапка разжималась, документ вырастал, привязка возвращала позицию обратно —
 * и всё повторялось КАЖДЫЙ КАДР. Замерено: 150 переключений за 2.5 секунды на
 * любой ширине, y скакал 104 → 9 → 104.
 *
 * Отсюда устройство: шапка вынута из потока (position: fixed), а её место
 * держит распорка постоянной высоты. Высота документа перестаёт зависеть от
 * состояния шапки, привязке прокрутки нечего компенсировать, петли нет по
 * построению — а не «почти нет при удачных порогах».
 *
 * ПОЧЕМУ ЗАМЕРОМ, А НЕ ЧИСЛОМ В CSS. Так и было: две объявленные переменные
 * складывались в месте залипания. Числа разошлись с настоящей высотой на 6px,
 * как только полоса шагов получила на широком экране шрифт покрупнее, и меню
 * срезало верхний пункт. Замеренная величина разойтись не может.
 *
 * ПОЧЕМУ ResizeObserver, А НЕ РАЗОВЫЙ ЗАМЕР. Шапка меняет высоту в работе:
 * переносится строка счётчика, приходит другой шрифт, поворачивают телефон.
 * Разовый замер устарел бы к первому же такому событию.
 *
 * Переменные пишем на корень оболочки, а не на documentElement: кабинет — не
 * единственный экран приложения, и глобальная переменная с его высотой
 * пережила бы его самого.
 */
export function useShellHeadHeight(
  head: Ref<HTMLElement | null>,
  root: Ref<HTMLElement | null>,
  /**
   * Сжата ли шапка сейчас. В сжатом виде полную высоту НЕ обновляем: распорка
   * обязана держать место под разжатую шапку, иначе она схлопнется вместе с
   * ней и вернёт ту самую петлю, ради которой всё и затевалось.
   */
  condensed: () => boolean,
): void {
  useResizeObserver(head, (entries) => {
    const target = root.value
    const entry = entries[0]
    if (target === null || entry === undefined) return

    /*
     * borderBoxSize, а не contentRect: у шапки снизу разделительная линия, и
     * без неё замер выходит на пиксель меньше настоящего — то есть с тем же
     * дефектом, только мельче.
     */
    const box = entry.borderBoxSize[0]
    const height = Math.round(box === undefined ? entry.contentRect.height : box.blockSize)

    target.style.setProperty('--vel-shell-head-h', `${height}px`)

    if (!condensed()) {
      target.style.setProperty('--vel-shell-head-full', `${height}px`)
    }
  })
}
