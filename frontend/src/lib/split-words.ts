/**
 * Разбор заголовка на слова — и правило доступности, которое к нему прилагается.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ. Разбором пользуются двое: заголовок первого
 * экрана (@/sections/VelHeroTitle.vue) и заголовки секций
 * (@/components/ui/VelSplitHeading.vue). Разъехавшиеся правила разбора дали бы
 * на одной странице две разные лесенки, а разъехавшийся приём доступности —
 * заголовок, который часть страницы читает целиком, а часть по словам.
 *
 * ПРАВИЛО ДОСТУПНОСТИ, обязательное для всех, кто зовёт splitWords().
 * Разбитый на слова текст ломает чтение вслух: каждое слово становится
 * отдельным inline-block, и часть скринридеров объявляет их по одному, с
 * паузами, а некоторые ещё и добавляют «список из N элементов». Поэтому
 * разобранная разметка ЦЕЛИКОМ помечается aria-hidden, а на самом заголовке
 * висит aria-label с полной строкой — это и есть его доступное имя. Роль
 * heading принимает имя из aria-label, поэтому скринридер читает «заголовок
 * 2-го уровня, <вся строка>», а лесенку видят только глаза.
 *
 * Дублирующей скрытой копии текста при этом не появляется: лишний узел попал бы
 * в поиск по странице и в машинный перевод. Тот же приём рекомендует GreenSock
 * для SplitText.
 */

/** Разбор строки на слова: пробелы схлопываем, пустые куски выбрасываем. */
export function splitWords(line: string): string[] {
  return line.split(/\s+/).filter((word) => word.length > 0)
}

/**
 * Шаг очереди между словами, с. 60 мс — слова успевают прочитаться как одна
 * фраза, а не как список: на 120 мс заголовок из шести слов растягивается
 * почти на секунду и начинает читаться по частям.
 */
export const WORD_STEP = 0.06

/** Подъём слова при появлении, px */
export const WORD_SHIFT = 20

/** Длительность появления одного слова, с */
export const WORD_DURATION = 0.55

export const WORD_EASE = 'power2.out'
