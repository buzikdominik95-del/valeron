<script setup lang="ts">
/**
 * Карточка программы — содержимое одной ячейки списка из
 * @/sections/VelPrograms.vue.
 *
 * КТО СТАНОВИТСЯ <li>. Роль <li> остаётся у VelReveal, а карточка сознательно
 * не заводит собственный корень. Причины:
 *
 * 1. Прямым ребёнком <ul role="list"> обязана быть ровно одна обёртка.
 *    Снаружи ею уже работает VelReveal с as="li" — он же несёт задержку
 *    появления, которая считается по индексу карточки, то есть принадлежит
 *    списку, а не отдельной карточке.
 * 2. Забрать <li> себе карточка не может: <li> внутри <li> — невалидная
 *    вложенность, а собственный <div> занял бы ячейку grid и развалил бы
 *    равные высоты карточек (ровно об этом предупреждает docblock VelReveal).
 *
 * Поэтому шаблон многокорневой: снимок и следом колонка с текстом.
 *
 * ПОЧЕМУ ЗДЕСЬ <img>, А НЕ VelPhoto. VelPhoto сделан под крупные врезки: он
 * растворяет края маской, кладёт сверху синий налёт и возит картинку
 * параллаксом внутри рамки. В ячейке размером с ладонь всё три работают
 * против неё — растворённый край в карточке с рамкой читается как незагрузка,
 * а параллакс на четырёх снимках сразу превращает спокойный ряд в рябь.
 * Плюс четыре контекста GSAP там, где хватает тега.
 *
 * ШИРИНА И ВЫСОТА ОБЯЗАТЕЛЬНЫ. Без них браузер не знает пропорцию до загрузки,
 * и ряд карточек прыгает, когда снимки приезжают. Пропорцию держит ещё и CSS
 * (aspect-ratio) — атрибуты нужны браузеру до применения стилей.
 */
interface Props {
  /** Название программы */
  title: string
  /** Пояснение под названием */
  text: string
  /** Снимок-иллюстрация: путь отдаёт сборщик, см. импорты в VelPrograms */
  photo: string
}

defineProps<Props>()
</script>

<template>
  <!--
    alt пустой намеренно: снимок здесь иллюстрация к заголовку, а не сообщение.
    Что это за программа, сказано следом словами — и заголовком, и абзацем.
    Описание вида «консультант за столом» скринридер зачитал бы четыре раза
    подряд перед четырьмя же заголовками, ничего к ним не добавив. Пустой alt
    убирает картинку из проговаривания; отсутствующий — заставил бы читать имя
    файла, поэтому атрибут именно пустой, а не пропущенный.

    loading/decoding ленивые: секция лежит ниже первого экрана.
  -->
  <img
    class="vel-program__photo"
    :src="photo"
    alt=""
    :width="1248"
    :height="832"
    loading="lazy"
    decoding="async"
  />

  <div class="flex flex-col gap-3 p-6">
    <!-- Квадрат-маркер повторяет акцент из шапки и ничего не сообщает -->
    <span class="size-1.5 bg-accent" aria-hidden="true"></span>
    <h3 class="text-lg">{{ title }}</h3>
    <p class="m-0 text-sm text-muted">{{ text }}</p>
  </div>
</template>

<style scoped>
/*
  Снимок занимает всю ширину ячейки и обрезается по 3:2. object-fit: cover
  обязателен: сами файлы 1248×832, но ячейка в четырёхколоночном ряду заметно
  уже, и без него картинка сжималась бы по горизонтали, а лица растягивались.

  Скругление только сверху: снизу у снимка соседи — текст, а не край карточки.
  Наследовать радиус нечем, поэтому берём тот же токен, что стоит на ячейке
  (rounded-panel), минус толщина рамки — иначе между рамкой и картинкой в углу
  остаётся видимый серп фона.
*/
.vel-program__photo {
  display: block;
  inline-size: 100%;
  block-size: auto;
  aspect-ratio: 3 / 2;
  object-fit: cover;
  border-start-start-radius: calc(var(--radius-panel) - 1px);
  border-start-end-radius: calc(var(--radius-panel) - 1px);
  /* Наезд снимка на наведении включает секция (см. .vel-programs__card:hover):
     сам переход живёт здесь, рядом со снимком, которому он и принадлежит. */
  transition: transform 320ms cubic-bezier(0.22, 1, 0.36, 1);
  /* Пока файл не приехал, на месте снимка спокойная подложка, а не белый
     провал в рамке. */
  background-color: var(--color-raised);
}
</style>
