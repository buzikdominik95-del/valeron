<script setup lang="ts">
/**
 * Шаг работы — содержимое одного пункта списка из
 * @/sections/VelHowWeWork.vue.
 *
 * КТО СТАНОВИТСЯ <li>. Роль <li> остаётся у VelReveal, собственного корня
 * у шага нет. Причины те же, что и у @/sections/VelProgramCard.vue:
 *
 * 1. Прямым ребёнком <ol role="list"> обязана быть ровно одна обёртка, и ею
 *    уже работает VelReveal с as="li".
 * 2. <li> внутри <li> — невалидная вложенность, а собственный <div> занял бы
 *    колонку grid и утащил бы разделители на себя.
 * 3. Разделители между шагами зависят от позиции в списке
 *    (:class="index > 0 ? ..."), как и задержка появления. Это знание списка,
 *    а не шага: шаг не должен знать, первый он или третий.
 *
 * Шаблон многокорневой и отдаёт номер, заголовок и текст — то, что раньше
 * лежало прямо внутри <li>. Классы пункта приходят снаружи на VelReveal.
 */
interface Props {
  /** Позиционный номер вида «01»: считается в списке, здесь только выводится */
  number: string
  /** Заголовок шага */
  title: string
  /** Пояснение под заголовком */
  text: string
}

defineProps<Props>()
</script>

<template>
  <span class="vel-num text-sm text-accent" aria-hidden="true">{{ number }}</span>
  <h3 class="text-xl">{{ title }}</h3>
  <!-- .vel-measure: на широком экране шаг живёт в узкой колонке, но ниже md
       колонки схлопываются в одну, и без меры строка доходила до 84 знаков
       (замер на 640). -->
  <p class="vel-measure text-sm text-muted">{{ text }}</p>
</template>
