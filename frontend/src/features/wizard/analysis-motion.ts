/**
 * Расписание живой проверки банков. Отдельный модуль по той же причине, что и
 * finalizing.ts: этими числами пользуются трое — строка (VelBankRow), список
 * (VelBankList) и таймер перехода в VelStepAnalysis. Разъехавшись, они дают
 * либо волну, оборванную сменой шага на середине, либо экран, который стоит
 * и ждёт давно закончившуюся анимацию.
 *
 * Источник истины ровно один — ANALYSIS_HANDOFF_MS. Остальное считается ИЗ него,
 * а не задаётся рядом с ним.
 */

/**
 * Условие для gsap.matchMedia(). Штатный механизм GSAP вместо ручной проверки
 * настройки: matchMedia сам подписывается на её смену и откатывает всё, что
 * создано внутри условия, когда пользователь просит не двигать интерфейс.
 * Ручная проверка отработала бы один раз при монтировании и на смену не
 * отозвалась бы.
 */
export const ANALYSIS_MOTION_OK = '(prefers-reduced-motion: no-preference)'

/**
 * Сколько экран ждёт после последней галочки, прежде чем уйти дальше.
 *
 * Потолок задан требованием и не обсуждается: пользователь ждёт результат,
 * а не представление. Внутрь этого бюджета обязана уложиться финальная волна
 * ЦЕЛИКОМ, вместе с разбросом по строкам.
 *
 * Переход висит на таймере, а не на onComplete волны: при
 * prefers-reduced-motion волна не создаётся вовсе, а скрытая вкладка не
 * получает кадров — обещание «анимация когда-нибудь закончится» не
 * выполняется, и пользователь остался бы на этом экране навсегда.
 */
export const ANALYSIS_HANDOFF_MS = 600

/** Подъём и возврат ОДНОЙ строки в волне: половина вверх, половина обратно. */
export const WAVE_ITEM_MS = 220

/** Тишина после волны и до смены шага: список успевает прочитаться целиком. */
const WAVE_TAIL_MS = 120

/**
 * Разброс волны сверху вниз — ОСТАТОК бюджета, а не отдельное число рядом.
 * Подрежут ANALYSIS_HANDOFF_MS — волна сожмётся сама, а не уедет за смену шага.
 *
 * Разброс задаётся GSAP через stagger.amount, то есть это время между стартом
 * ПЕРВОЙ и ПОСЛЕДНЕЙ строки. Длина списка на длительность волны не влияет:
 * тринадцать строк или тридцать — волна занимает ровно этот отрезок.
 */
export const WAVE_SPREAD_MS = Math.max(0, ANALYSIS_HANDOFF_MS - WAVE_TAIL_MS - WAVE_ITEM_MS)

/**
 * Насколько строка приподнимается в волне. Именно transform: подъём через top
 * или margin пересчитывал бы раскладку всего списка на каждом кадре, и
 * тринадцать строк дёргались бы вместо волны.
 */
export const WAVE_LIFT_PX = 4

/**
 * ПОЯВЛЕНИЕ СПИСКА. Строки выезжают снизу друг за другом, а не возникают
 * пачкой: тринадцать одинаковых прямоугольников, включившихся одновременно,
 * глаз читает как один серый блок и начинает разбирать его с нуля. Очередь
 * задаёт направление чтения — сверху вниз, туда же, куда пойдёт опрос.
 *
 * Числа держатся здесь, рядом с волной, по той же причине, что и она:
 * появление и финальный жест — два конца одного экрана, и разъехавшись
 * они дают список, который въезжает дольше, чем проверяется.
 */

/** Сколько едет ОДНА строка при появлении. */
export const ENTER_ITEM_MS = 380

/**
 * Разброс появления между ПЕРВОЙ и ПОСЛЕДНЕЙ строкой (stagger.amount).
 * Именно amount, а не задержка на строку: иначе тридцать банков въезжали бы
 * втрое дольше тринадцати, и половина списка появлялась бы уже проверенной.
 */
export const ENTER_SPREAD_MS = 420

/** Насколько строка выезжает снизу. Только transform — раскладка не трогается. */
export const ENTER_LIFT_PX = 14
