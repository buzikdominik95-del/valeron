/**
 * Показательные условия предложения и арифметика к ним.
 *
 * Отдельный модуль по той же причине, что finalizing.ts и analysis-motion.ts:
 * это данные и чистые функции, а не разметка. Срок и ставка объявлены здесь
 * заранее, одобренная сумма считается от запрошенной. Когда появится бэкенд,
 * эти значения придут из ответа, и править придётся ровно один файл, а не шаг
 * целиком.
 *
 * Числа намеренно свои, а не из стора калькулятора: там срок и сумму двигает
 * пользователь, а здесь стоят условия УЖЕ ВЫДАННОГО предложения — двигаться
 * им нечем.
 */

/** Показательные условия предложения. */
export const TERM_MONTHS = 36
export const ANNUAL_RATE_PERCENT = 3.8

/** Платёж показываем с центами: округление до евро прячет разницу в условиях. */
export const MONTHLY_FORMAT = {
  key: 'currency',
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
} as const

/**
 * Насколько одобренная сумма меньше запрошенной: от 15% до 20%.
 * Границы включительные — 15% и 20% достижимы.
 */
const CUT_MIN = 0.15
const CUT_MAX = 0.2

/** Шаг округления результата, евро. Одобрение в «13 447 €» читается как
    ошибка счёта; банк называет круглое число. */
const CUT_ROUND_TO = 100

/**
 * Одобренная сумма по запрошенной: меньше на 15…20%.
 *
 * ПОЧЕМУ НЕ СЛУЧАЙНО. Math.random() здесь дал бы новую сумму на каждой
 * перерисовке: экран результата и карточка кабинета показывали бы разные
 * цифры по одной заявке, а перезагрузка страницы меняла бы «одобрено» на
 * глазах у человека. Доля выводится ИЗ САМОЙ СУММЫ, поэтому она устойчива:
 * один и тот же запрос всегда даёт один и тот же ответ, а разные суммы —
 * разные доли, и одинакового процента на всех не видно.
 *
 * Шаг сетки калькулятора — 500 €, поэтому делим на него: иначе соседние
 * положения ползунка давали бы одну и ту же долю.
 *
 * Функция чистая: её легко проверить, не запуская приложение.
 *   16000 → доля 0.17 → 13280 → округление вниз до сотни → 13 200 €
 */
export function approvedFromRequested(requested: number): number {
  if (!Number.isFinite(requested) || requested <= 0) return 0

  const steps = Math.round(CUT_MAX * 100 - CUT_MIN * 100) + 1
  const cut = CUT_MIN + (Math.abs(Math.round(requested / 500)) % steps) / 100

  const reduced = requested * (1 - cut)
  return Math.floor(reduced / CUT_ROUND_TO) * CUT_ROUND_TO
}

/**
 * Аннуитетный (равный) ежемесячный платёж.
 *
 *        S · i
 *   P = ---------------,  i = годовая ставка / 100 / 12,  n = срок в месяцах
 *       1 − (1 + i)⁻ⁿ
 *
 * При нулевой ставке формула вырождается: делить на ноль нельзя, платёж
 * становится простым делением суммы на срок. Функция чистая — её результат
 * сверяется калькулятором аннуитета без запуска приложения.
 */
export function annuityPayment(
  principal: number,
  annualRatePercent: number,
  months: number,
): number {
  if (months <= 0) return 0

  const monthlyRate = annualRatePercent / 100 / 12
  if (monthlyRate === 0) return principal / months

  return (principal * monthlyRate) / (1 - Math.pow(1 + monthlyRate, -months))
}
