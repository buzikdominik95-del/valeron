/**
 * Расписание экрана финализации. Отдельный модуль, потому что этими числами
 * пользуются сразу двое: таймер перехода на результат (useTimeoutFn) и
 * анимация полосы прогресса (GSAP). Разъехавшись, они дают либо рывок —
 * полоса ещё едет, а шаг уже сменился, — либо застывшую полосу, которая
 * доехала и стоит, пока экран висит.
 *
 * Поэтому источник истины ровно один: FINALIZING_TOTAL_MS. Всё остальное
 * здесь считается ИЗ него, а не задаётся рядом с ним.
 */

/**
 * Столько экран висит перед переходом на результат — и ровно столько же
 * заполняется полоса прогресса под ним. Менять только здесь.
 */
export const FINALIZING_TOTAL_MS = 2500

/**
 * Стадии оформления в порядке показа. Порядок задаёт ИМЕННО этот список,
 * а не порядок ключей в файле локали: ключи в объекте переставит первый же
 * автоформат, и подписи поедут, ничего не сломав явно.
 *
 * Ключ читается как t('wizard.finalizing.steps.<key>').
 */
export const FINALIZING_STEP_KEYS = ['profile', 'banks', 'rate', 'offer'] as const

export type FinalizingStepKey = (typeof FINALIZING_STEP_KEYS)[number]

/** Шаг смены подписей по макету. */
const FINALIZING_CAPTION_DESIGN_MS = 600

/**
 * Сколько на самом деле живёт одна подпись.
 *
 * Обычно это ровно значение из макета: 4 стадии × 600 мс = 2400 мс, и
 * последняя успевает побыть на экране ещё 100 мс до перехода. Но потолок
 * взят не зря: стоит добавить в FINALIZING_STEP_KEYS пятую стадию — и при
 * жёстких 600 мс она вышла бы на 2400 мс, а шестая не показалась бы вовсе,
 * потому что экран к тому времени уже сменился. Деление на длину списка
 * сжимает шаг ровно настолько, чтобы весь набор помещался в отведённое время.
 */
export const FINALIZING_CAPTION_MS = Math.min(
  FINALIZING_CAPTION_DESIGN_MS,
  FINALIZING_TOTAL_MS / FINALIZING_STEP_KEYS.length,
)

/**
 * Условие для gsap.matchMedia(). Штатный механизм GSAP вместо ручной проверки
 * настройки: matchMedia сам подписывается на её смену и откатывает всё, что
 * было создано внутри условия, когда пользователь просит не двигать интерфейс.
 * Ручная проверка отработала бы один раз при монтировании и на смену
 * не отозвалась бы.
 */
export const FINALIZING_MOTION_OK = '(prefers-reduced-motion: no-preference)'
