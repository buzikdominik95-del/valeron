/**
 * Файл логотипа банка — если он вообще положен в src/img/banks.
 *
 * ПОЧЕМУ ЭТО НЕ ПРОТИВОРЕЧИТ ЗАПРЕТУ НА ЧУЖИЕ ЗНАКИ. Логотипы банков — чужие
 * товарные марки, и в репозитории их нет: папка src/img/banks приезжает пустой,
 * с одним README. Здесь заведён только МЕХАНИЗМ подстановки — на тот день,
 * когда у владельца продукта появится договор с банком или письменное
 * разрешение и файл можно будет положить законно. До того дня марка рисуется
 * сама (@/features/wizard/bank-mark-identity), и отсутствие файла — обычное
 * рабочее состояние, а не сломанная картинка.
 *
 * ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ КУСОК VelBankMark.vue: там уже лежит разбор форм,
 * цветов и контрастов, и файл упирался бы в лимит в 300 строк. Соседний
 * bank-mark-identity.ts устроен так же — «как выглядит марка» и «откуда она
 * берётся» стоят рядом с компонентом, но не внутри него.
 *
 * ПОЧЕМУ import.meta.glob С eager: true.
 *
 * Список файлов раскрывает СБОРЩИК: Vite подставляет сюда статические импорты
 * ровно тех файлов, что реально лежат в папке. Из этого следует главное
 * свойство — БИТОЙ КАРТИНКИ БЫТЬ НЕ МОЖЕТ. В разметку попадает только путь,
 * который сборка нашла и положила в бандл; ни 404, ни пустого квадрата,
 * ни обработчика @error, который прятал бы уже мигнувшую «сломанную» иконку.
 * Проверка «есть файл или нет» происходит один раз при сборке, а не у каждого
 * посетителя в рантайме.
 *
 * Пустая папка при этом законна: glob без совпадений даёт пустой объект,
 * ни один банк логотипа не найдёт, и все тринадцать строк покажут
 * генерируемую марку — то есть ровно то, что на экране сейчас.
 *
 * query: '?url' вместо голого импорта — намеренно. Сейчас Vite и так отдал бы
 * ссылку на файл, но стоит кому-нибудь подключить плагин, превращающий .svg
 * в Vue-компонент (vite-svg-loader и подобные), — и голый импорт вернул бы
 * объект компонента, который в src="" превратился бы в «[object Object]».
 * С явным '?url' ответ остаётся ссылкой при любых плагинах.
 */

/**
 * Порядок предпочтения расширений: вектор лучше растра, а из растровых
 * форматов первым идёт png — прозрачность в нём есть везде и без оговорок,
 * тогда как webp обычно приходит уже пережатым с чужого сайта.
 *
 * Тип — readonly string[], а не кортеж литералов: ниже по этому массиву идёт
 * indexOf() от расширения ФАЙЛА, то есть от произвольной строки, и кортеж
 * литералов заставил бы приводить типы там, где приводить нечего.
 */
const EXTENSION_PRIORITY: readonly string[] = ['svg', 'png', 'webp']

/**
 * Всё, что лежит в папке. Ключ — путь файла, значение — ссылка на него
 * после сборки. Шаблон обязан быть литералом: он читается статически.
 */
const FILES = import.meta.glob('@/img/banks/*.{svg,png,webp}', {
  eager: true,
  query: '?url',
  import: 'default',
})

interface LogoFile {
  /** Ссылка на файл после сборки. */
  url: string
  /** Место расширения в EXTENSION_PRIORITY: меньше — предпочтительнее. */
  rank: number
}

/**
 * Имя банка → имя файла без расширения.
 *
 * Правило целиком: снять диакритику, опустить регистр, любой кусок из прочих
 * символов (пробелы, точки, `&`, апострофы) заменить одним дефисом, дефисы по
 * краям убрать. «Intesa Sanpaolo» → `intesa-sanpaolo`, «Crédit Agricole» →
 * `credit-agricole`, «J.P. Morgan» → `j-p-morgan`.
 *
 * Диакритика снимается через NFD: разложенная форма держит букву и знак над
 * ней отдельными символами, и знак остаётся выбросить по его блоку Unicode.
 * Без этого «é» осталась бы одним символом, который не попадает ни в a-z,
 * ни в цифры, — и «Crédit» дал бы `cr-dit`.
 *
 * Правило одно на обе стороны: и на имя банка, и на имя найденного файла.
 * Иначе `Intesa Sanpaolo.svg`, положенный руками с пробелом и заглавными,
 * молча не находился бы — а человек видел бы «механизм не работает».
 */
export function bankFileSlug(name: string): string {
  return name
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

/**
 * Разбор папки в таблицу «слаг → файл». Считается один раз при загрузке
 * модуля: содержимое папки после сборки не меняется, а марок на экране
 * тринадцать, и перебирать файлы на каждую перерисовку незачем.
 */
function buildIndex(): ReadonlyMap<string, LogoFile> {
  const index = new Map<string, LogoFile>()

  for (const [path, url] of Object.entries(FILES)) {
    const file = path.slice(path.lastIndexOf('/') + 1)
    const dot = file.lastIndexOf('.')
    const rank = EXTENSION_PRIORITY.indexOf(file.slice(dot + 1).toLowerCase())
    const slug = bankFileSlug(file.slice(0, dot))

    // rank === -1 сюда не приходит (glob отбирает три расширения), но проверка
    // стоит: она же ловит файл без точки в имени, у которого dot === -1.
    if (slug === '' || rank === -1) continue

    const current = index.get(slug)

    // Строго «меньше», а не «меньше или равно»: при равном ранге (то есть
    // одинаковом расширении) побеждает первый найденный, и порядок обхода
    // папки не превращается в лотерею.
    if (current === undefined || rank < current.rank) index.set(slug, { url, rank })
  }

  return index
}

const LOGO_BY_SLUG = buildIndex()

/**
 * Ссылка на логотип банка или undefined, если файла нет.
 *
 * undefined, а не null: значение уходит прямо в :src, где Vue выбрасывает
 * атрибут целиком, — и ни один пустой src в разметку не попадает.
 */
export function bankLogoFile(name: string): string | undefined {
  const slug = bankFileSlug(name)

  // Имя из одних нелатинских букв («Сбер») схлопывается в пустой слаг.
  // Без этой проверки пустой ключ мог бы совпасть с мусорным файлом
  // вроде `-.svg` и подставить его вообще всем таким банкам.
  if (slug === '') return undefined

  return LOGO_BY_SLUG.get(slug)?.url
}
