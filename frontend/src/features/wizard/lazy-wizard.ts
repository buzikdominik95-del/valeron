import { defineAsyncComponent } from 'vue'

/**
 * Мастер заявки отдельным куском — и заранее прогретый.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ КУСКОМ. Мастер это семь шагов со своей оболочкой, списком
 * банков и двумя экранами ожидания — около 10 kB gzip. Лендинг открывают все,
 * а мастер — те, кто дошёл до кнопки «рассчитать», и держать его в общем файле
 * значит отдавать этот код каждому, включая тех, кто закроет вкладку на первом
 * экране.
 *
 * ПОЧЕМУ ЭТО НЕ ДАЁТ ПАУЗЫ. Голая ленивая загрузка поставила бы ожидание сети
 * ровно в тот момент, когда человек нажал главную кнопку страницы, — худшее
 * место для паузы, и прошлая правка отказалась от неё именно поэтому.
 * Здесь кусок начинает грузиться РАНЬШЕ нажатия: калькулятор зовёт
 * prefetchWizard(), как только с ним начали взаимодействовать (см. VelSimulator).
 * Между наведением на форму и нажатием «Calcola» человек успевает выбрать цель
 * и сумму — секунды, за которые кусок в 10 kB приезжает с любого канала.
 *
 * То есть выигрыш в весе первого экрана есть, а паузы на переходе нет:
 * к моменту нажатия модуль уже в кеше модулей, и defineAsyncComponent отдаёт
 * его синхронно.
 */
/** Единственная точка загрузки: её же зовут и компонент, и прогрев. */
const load = () => import('@/features/wizard/VelWizardFlow.vue')

export const VelWizardFlowAsync = defineAsyncComponent(load)

/** Загрузка уже запущена — второй раз сеть не трогаем. */
let warmed = false

/**
 * Начать загрузку мастера, не показывая его. Вызывается по первому признаку
 * намерения (наведение или фокус в калькуляторе). Идемпотентна: браузер и так
 * не скачает модуль дважды, но лишний промис заводить незачем.
 */
export function prefetchWizard(): void {
  if (warmed) return
  warmed = true
  void load()
}
