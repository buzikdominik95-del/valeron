/**
 * Номер договора и его календарь: всё, что ВЫВЕДЕНО из заявки, а не посчитано
 * калькулятором.
 *
 * Отдельным модулем от contract-data.ts: здесь нет ни одного computed и ни
 * одного обращения к сторам — чистые функции над строкой и датой. Значения
 * листа договора собирает соседний модуль, а этот отвечает ровно за то,
 * чтобы номер и даты были УСТОЙЧИВЫМИ.
 */

/**
 * Момент, которым датирован договор. Считается ОДИН РАЗ на загрузку вкладки,
 * а не в computed.
 *
 * Почему так: от этой даты зависит номер договора, а номер обязан быть
 * неподвижным. Возьми мы new Date() внутри вычисления — номер и дата менялись
 * бы при каждом пересчёте, и человек видел бы, как «его» договор переписывает
 * сам себя, пока он листает страницу.
 */
export const ISSUED_AT = new Date()

/** Смещения FNV-1a: 32-битный хэш без зависимостей, детерминированный. */
const FNV_OFFSET = 0x811c9dc5
const FNV_PRIME = 0x01000193

/** Сколько знаков в серийной части номера. */
const SERIAL_LENGTH = 7

/** День месяца, на который приходится первый платёж — как в «Dettagli del prestito». */
const FIRST_PAYMENT_DAY = 25

/**
 * Хэш строки заявки. Нужен ровно для одного: получить из данных заявки
 * устойчивый номер договора.
 *
 * ПОЧЕМУ НЕ СЛУЧАЙНОЕ ЧИСЛО. Случайный номер меняется при каждой перерисовке
 * компонента: человек уходит на вкладку «Documenti», возвращается — и договор
 * у него уже другой. Номер, выведенный из самой заявки, при тех же данных
 * всегда один и тот же, и при этом у двух разных заявок он разный.
 *
 * Math.imul, а не обычное умножение: произведение выходит за 2^53, и без
 * него хэш начал бы терять младшие разряды.
 */
function hashApplication(seed: string): number {
  let hash = FNV_OFFSET
  for (let index = 0; index < seed.length; index += 1) {
    hash ^= seed.charCodeAt(index)
    hash = Math.imul(hash, FNV_PRIME)
  }
  return hash >>> 0
}

/**
 * Номер договора вида «VLR-2026-1A2B3C4».
 *
 * В зерне — всё, что отличает одну заявку от другой: кто, на сколько, на какой
 * срок и под какой процент; собирает его вызывающая сторона. Год берётся
 * из даты договора, поэтому номер читается как настоящий, оставаясь при этом
 * выведенным, а не сочинённым.
 */
export function contractNumber(seed: string): string {
  const serial = hashApplication(seed).toString(36).toUpperCase().padStart(SERIAL_LENGTH, '0')
  return `VLR-${ISSUED_AT.getFullYear()}-${serial}`
}

/** ISO-дата первого платежа: 25-е число следующего месяца от даты договора. */
export function firstPaymentIso(from: Date): string {
  const date = new Date(Date.UTC(from.getFullYear(), from.getMonth() + 1, FIRST_PAYMENT_DAY))
  return date.toISOString().slice(0, 10)
}

/** Строка вида 'YYYY-MM-DD' → Date в UTC. Без UTC день уезжает на часовой пояс. */
export function fromIsoDate(iso: string): Date {
  return new Date(`${iso}T00:00:00Z`)
}
