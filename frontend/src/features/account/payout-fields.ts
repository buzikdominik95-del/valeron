import { IBAN_MAX_LENGTH, IBAN_MIN_LENGTH } from '@/lib/iban'
import type { PayoutMethod } from '@/api/account.api'

/**
 * Правила ввода реквизитов — одна таблица на оба способа получения.
 *
 * Отдельным модулем, а не константой в модалке: маска, границы длины и вид
 * клавиатуры описывают ПОЛЕ, а не окно, и проверяются чтением таблицы, без
 * запуска приложения. Модалка берёт отсюда готовое правило по выбранному
 * способу и сама ничего о форматах не знает.
 *
 * Границы взяты из стандартов, а не подобраны на глаз: занизив максимум, мы
 * обрезали бы валидный чужой IBAN, а завысив минимум — заблокировали бы кнопку
 * на верных реквизитах.
 */
export interface PayoutAccountRule {
  /** Максимум значащих символов. Больше в поле просто не попадёт. */
  max: number
  /** Минимум, ниже которого отправлять нечего. */
  min: number
  /** Приводить к верхнему регистру. */
  upper: boolean
  /**
   * Что считается значащим символом. Без флага g: маска зовёт test()
   * на одном и том же выражении много раз, см. useMaskedInput.
   */
  allow: RegExp
  /** Какую клавиатуру звать на телефоне. */
  inputMode: 'text' | 'numeric'
  /**
   * Токен автозаполнения поля реквизитов. У номера карты он стандартный
   * (cc-number) и включает подстановку из менеджера карт; у IBAN такого токена
   * в HTML нет вовсе, и «off» здесь честнее выдуманного имени — иначе браузер
   * подставит в поле счёта что-нибудь своё, вроде адреса.
   */
  autocomplete: string
  /** Токен автозаполнения для имени держателя — оно тоже разное у способов. */
  holderAutocomplete: string
}

export const PAYOUT_ACCOUNT_RULES: Record<PayoutMethod, PayoutAccountRule> = {
  /*
   * IBAN по ISO 13616: латиница и цифры, от 15 символов (Норвегия) до 34.
   * Итальянский — 27, но поле обязано принять и зарубежный счёт: клиент вправе
   * получить деньги не на итальянский банк. Регистр верхний — код страны и
   * контрольные разряды записываются заглавными.
   *
   * Границы берутся из @/lib/iban, где по ним же считается контрольная сумма:
   * своя пара чисел здесь однажды разошлась бы с проверкой, и поле принимало
   * бы строку, которую сама же проверка объявляет негодной.
   */
  iban: {
    max: IBAN_MAX_LENGTH,
    min: IBAN_MIN_LENGTH,
    upper: true,
    allow: /[0-9A-Za-z]/,
    inputMode: 'text',
    autocomplete: 'off',
    holderAutocomplete: 'name',
  },

  /*
   * Номер карты по ISO/IEC 7812: до 19 цифр, короче 13 не бывает. Проверку
   * Луна намеренно не делаем: она отсеивает опечатки, но здесь превратилась бы
   * в приговор «карта неверна» от фронта, у которого на это нет полномочий.
   */
  card: {
    max: 19,
    min: 13,
    upper: false,
    allow: /[0-9]/,
    inputMode: 'numeric',
    autocomplete: 'cc-number',
    holderAutocomplete: 'cc-name',
  },
}

/** Имя держателя: два символа — минимальная осмысленная строка. */
export const HOLDER_MIN_LENGTH = 2
