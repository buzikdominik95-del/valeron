<script setup lang="ts">
import { computed } from 'vue'
import { useI18n } from 'vue-i18n'
import { useAccountView } from '@/composables/useAccountView'
import { useCabinetTab } from '@/composables/useCabinetTab'
import { useCommission } from '@/composables/useCommission'
import VelLogo from '@/components/ui/VelLogo.vue'
import VelTrackerBar from '@/features/account/VelTrackerBar.vue'
import VelCabinetUser from '@/features/account/VelCabinetUser.vue'

/**
 * ЗАЛИПАЮЩАЯ ШАПКА кабинета: полоса со знаком, блоком пользователя
 * и колокольчиком — и трекер пяти шагов под ней.
 *
 * С L2+ полоса шагов СКРЫТА (как на референсе этапов 2–4).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Оболочка (VelAccount) отвечает за расклад экрана:
 * рама, место под открытый раздел, заставка. Шапка — самостоятельный кусок со
 * своей разметкой, своими подписями для скринридера и большей частью всех
 * стилей кабинета; вместе они давали файл, в котором расклад приходилось
 * искать между правилами колокольчика.
 *
 * ЗДЕСЬ ТОЛЬКО СТРОКА И ЕЁ РАСКЛАД. Правый угол (блок пользователя,
 * колокольчик) вынесен в VelCabinetUser — по той же причине, по которой сама
 * шапка отделена от оболочки: у него своя, ни с чем не связанная работа.
 *
 * КЛАССЫ ОСТАЛИСЬ vel-cabinet__…, хотя файл теперь свой. Это по-прежнему
 * элементы блока «кабинет», а не новый блок: переезд чисто файловый, в DOM
 * не поменялось ничего. Переименование сломало бы внешние проверки — по
 * классам этого блока ходит scripts/audit-mobile.mjs.
 *
 * ШАПКА ОСТАЁТСЯ СВЕТЛОЙ — осознанное расхождение с эталоном. Там полоса
 * тёмная, с вывороткой. У нас логотип и контролы собраны под светлый фон.
 * Структура эталонная: слева знак, справа человек и уведомления.
 */
const { t } = useI18n()
const { close } = useAccountView()
const { tab, select: selectTab } = useCabinetTab()
const { level } = useCommission()

/** Уведомления открывает тот, кто соберёт их экран, — шапка только сообщает. */
const emit = defineEmits<{ notices: [] }>()

/** Полоса 5 шагов только на этапе 1 (level === 1). */
const showStepBar = computed(() => level.value <= 1)

/**
 * Логотип: из профиля/документов/чата — на Home кабинета (первый экран),
 * уже с Home — выход на лендинг. Иначе с профиля «домой» не попадали.
 */
function onLogoClick(): void {
  if (tab.value !== 'home') {
    selectTab('home')
    return
  }
  close()
}

/*
 * Сжата ли шапка — решает оболочка (VelAccount): то же состояние нужно
 * замеру высот, который держит распорку под шапкой. Два независимых
 * наблюдателя за одной прокруткой разошлись бы на кадр, и распорка ловила
 * бы высоту не того состояния.
 */
const props = defineProps<{ condensed: boolean }>()
</script>

<template>
  <header
    class="vel-cabinet__header"
    :class="{
      'vel-cabinet__header--tight': props.condensed,
      'vel-cabinet__header--no-track': !showStepBar,
    }"
  >
    <div class="vel-cabinet__bar">
      <button
        type="button"
        class="vel-cabinet__home"
        :aria-label="t('account.shell.home')"
        @click="onLogoClick"
      >
        <VelLogo />
      </button>

      <!--
        Полоса шагов лежит В ТОЙ ЖЕ строке, что логотип и блок пользователя, и
        занимает всю её ширину — из-за flex-wrap это переносит её на вторую
        строку. Сжимаясь, она перестаёт занимать всю ширину и встаёт в просвет
        между логотипом и аватаром: шапка становится однострочной.
        С L2+ полосы нет — шапка однострочная всегда.
      -->
      <VelTrackerBar
        v-if="showStepBar"
        :condensed="props.condensed"
        class="vel-cabinet__track"
      />

      <VelCabinetUser @notices="emit('notices')" />
    </div>
  </header>
</template>

<style scoped>
/*
  Высота полосы (--vel-header-h) и высота трекера (--vel-track-h) объявлены
  на .vel-cabinet в оболочке и приходят сюда наследованием: от них считаются
  залипание меню и sticky-колонка Home, поэтому число обязано быть одно на всех.
*/
/*
  ШАПКА ВЫНУТА ИЗ ПОТОКА, и это не украшение раскладки, а лечение петли.

  Пока она была sticky, её сжатие уменьшало высоту документа на 95px. Браузер
  компенсировал это собственной привязкой прокрутки (scroll anchoring) —
  подтягивал позицию на те же 95px, чтобы содержимое не прыгнуло. Позиция
  уезжала ниже порога разжатия, шапка разжималась, документ вырастал, привязка
  возвращала позицию обратно — и всё повторялось каждый кадр. Замерено:
  150 переключений за 2.5 секунды на любой ширине, y скакал 104 → 9 → 104.

  Вне потока высота шапки на документ не влияет вовсе, компенсировать нечего,
  и петля невозможна по построению. Место под неё держит распорка
  .vel-cabinet__headroom постоянной высоты — см. VelAccount.

  inset-inline: 0 обязателен: у fixed-элемента без него ширина считается по
  содержимому, и полоса схлопнулась бы до логотипа с аватаром.
*/
.vel-cabinet__header {
  position: fixed;
  inset-block-start: 0;
  inset-inline: 0;
  /* Выше меню (30), ниже панели уведомлений (50) и заставки (60) */
  z-index: 40;
  border-block-end: 1px solid var(--color-line);
  background-color: var(--color-surface);
}

/* L2+: без полосы шагов — однострочная шапка */
.vel-cabinet__header--no-track .vel-cabinet__bar {
  flex-wrap: nowrap;
}

.vel-cabinet__bar {
  display: flex;
  /* Перенос — единственный способ держать полосу шагов и в отдельной строке,
     и в общей, не заводя вторую копию разметки. */
  flex-wrap: wrap;
  min-block-size: var(--vel-header-h);
  align-items: center;
  gap: 0.5rem;
  /* Не меньше 0.875rem, а в ландшафте с вырезом — не меньше выреза (см. ниже
     про viewport-fit=cover). Без выреза env() = 0, отступ прежний. */
  padding-inline:
    max(0.875rem, env(safe-area-inset-left))
    max(0.875rem, env(safe-area-inset-right));
}

/*
  РАЗЖАТАЯ ПОЛОСА ШАГОВ занимает всю ширину строки и потому переносится под
  логотип. order: 1 ставит её ПОСЛЕ блока пользователя в раскладке, оставаясь
  перед ним в разметке: на второй строке ей и место, а в порядке обхода с
  клавиатуры шаги идут раньше — они про заявку, а не про настройки.
*/
.vel-cabinet__track {
  order: 1;
  flex: 1 0 100%;
  min-inline-size: 0;
}

/*
  СЖАТАЯ — обычный средний элемент строки: встаёт в просвет между логотипом и
  аватаром, и шапка становится однострочной.

  flex-grow ЗДЕСЬ ОБЯЗАН БЫТЬ НУЛЁМ. С единицей полоса забирала всю свободную
  ширину, блок пользователя переставал помещаться в остаток и переносился на
  вторую строку — шапка «сжималась» со 152px до 99 вместо 56, то есть
  выглядела сломанной ровно там, где должна была стать компактной. Расти ей
  незачем: ширину она берёт по содержимому, а вправо блок пользователя
  прижимает своё margin-inline-start: auto.

  Сжиматься (flex-shrink: 1) при этом можно и нужно: на самом узком экране
  лучше подрезать полосу, чем выдавить аватар за край.
*/
@media (min-width: 48rem) {
  .vel-cabinet__header--tight .vel-cabinet__track {
    order: 0;
    flex: 0 1 auto;
  }
}

/*
  НА ТЕЛЕФОНЕ СЖАТАЯ ПОЛОСА ОСТАЁТСЯ НА СВОЕЙ СТРОКЕ — то есть правило выше
  сюда намеренно не распространяется. В строку она там не влезает: логотип
  87 + блок пользователя 190 + поля 28 + зазоры 16 при 390px оставляют около
  69px, а полосе нужно 85. Втиснутая силой, она выдавливала блок пользователя
  на вторую строку, и шапка «сжималась» со 152px до 99 вместо 57 — то есть
  выглядела сломанной ровно там, где должна была стать компактной.

  Оставаясь во всю ширину, она схлопывается до линии в 3px под строкой шапки:
  места по горизонтали не просит вовсе и работает на любой ширине.
*/

/* Кнопка-логотип: у неё нет ни фона, ни рамки — щёлкают по самому знаку.
   Кольцо фокуса остаётся из base, поэтому с клавиатуры она видна. */
.vel-cabinet__home {
  display: inline-flex;
  /* Цель нажатия: знак остаётся прежнего размера, растёт только прямоугольник
     попадания — до 44 по высоте (WCAG 2.5.5). */
  min-block-size: 2.75rem;
  align-items: center;
  padding: 0;
  border: 0;
  border-radius: var(--radius-control);
  background: transparent;
  cursor: pointer;
  transition: opacity 150ms ease;
}

.vel-cabinet__home:hover {
  opacity: 0.75;
}

.vel-cabinet__home:active {
  opacity: 0.55;
}

@media (prefers-reduced-motion: reduce) {
  .vel-cabinet__home {
    transition: none;
  }
}
</style>
