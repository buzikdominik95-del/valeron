/**
 * Геометрия канваса подписи: размеры, подгонка области и координаты точек.
 *
 * Отдельным модулем от самой отрисовки (signature-canvas.ts): здесь нет ни
 * одного вызова 2d-контекста — только числа, и проверяются они чтением, без
 * канваса вовсе. Отрисовка же берёт отсюда готовый прямоугольник и не считает
 * ничего сама.
 *
 * Точки хранятся НОРМИРОВАННЫМИ (0…1 по каждой оси), а не в пикселях.
 * Канвас резиновый: поворот телефона или изменение окна меняет его ширину,
 * и подпись, записанная в пикселях, уехала бы за край и обрезалась.
 *
 * Одних долей, однако, мало. Область меняет не только размер, но и ФОРМУ:
 * высота ходит по clamp(9rem, 34vw, 12.5rem), ширина — по ширине окна, и
 * соотношение сторон между 375 и 1280 отличается заметно. Доли, пересчитанные
 * в новый прямоугольник напрямую, растянули бы росчерк по одной оси и сплющили
 * по другой — а подпись это её форма, искажённая подпись это другая подпись.
 *
 * Поэтому доли считаются от ОБЛАСТИ ЗАПИСИ (origin) — той, в которой подпись
 * поставили, — а под текущую область они подгоняются только в момент
 * отрисовки: масштаб единый по обеим осям, остаток места уходит в поля.
 *
 * ПОЧЕМУ ИМЕННО ТАК, А НЕ ПЕРЕСЧЁТОМ ТОЧЕК НА МЕСТЕ. Здесь раньше стояла
 * функция rebase, которая при каждой смене размера переписывала координаты.
 * Один пересчёт она делала верно, но операция НЕОБРАТИМА: она вписывает всю
 * прежнюю область в новую, а у области нет постоянной пропорции. Круг
 * «повернул телефон и вернул обратно» перемножал масштабы в
 * (w_узкой × h_широкой) / (w_широкой × h_узкой) — для замеренных 281×140
 * и 544×200 это 0.74. То есть подпись НАВСЕГДА становилась 74% от себя,
 * пять поворотов — 22%, и исходных координат, чтобы это отменить,
 * уже не существовало.
 *
 * Сейчас источник неприкосновенен: сколько угодно поворотов возвращают
 * подпись ровно такой, какой её поставили. Подпись — юридический след,
 * тихо усыхать он не имеет права.
 */

/**
 * Ближе этого (CSS-пиксели) новая точка не запоминается. Сенсорные экраны
 * шлют россыпь почти совпадающих координат, и на них сглаживание начинает
 * дрожать: контрольные точки квадратичной кривой лежат друг на друге.
 */
const MIN_STEP = 1.1

/** Точка штриха в долях от размера канваса. */
export interface Point {
  x: number
  y: number
}

/** Размер области рисования в CSS-пикселях. */
export interface Size {
  width: number
  height: number
}

/**
 * Прямоугольник, в который область записи вписана внутри текущей области:
 * положение левого верхнего угла и размер, оба в CSS-пикселях.
 */
export interface FitBox {
  offsetX: number
  offsetY: number
  width: number
  height: number
}

function clamp01(value: number): number {
  return Math.min(1, Math.max(0, value))
}

/**
 * Вписывает область записи в текущую с сохранением пропорций.
 *
 * Масштаб — наименьший из двух отношений, поэтому подпись целиком помещается
 * и не деформируется. Свободный остаток делится поровну, то есть росчерк
 * стоит по центру, а не прижимается к углу.
 */
function fitBox(from: Size, to: Size): FitBox {
  const scale = Math.min(to.width / from.width, to.height / from.height)
  const width = from.width * scale
  const height = from.height * scale

  return {
    offsetX: (to.width - width) / 2,
    offsetY: (to.height - height) / 2,
    width,
    height,
  }
}

/**
 * Куда область записи попадает внутри текущей прямо сейчас.
 *
 * Пока штрихов нет, областью записи считается сама текущая — подгонка
 * получается тождественной, и первый штрих ложится один в один под курсор.
 * null означает, что мерить нечего: область ещё не разложена.
 */
export function currentBox(origin: Size | null, size: Size): FitBox | null {
  const { width, height } = size
  if (width === 0 || height === 0) return null

  return fitBox(origin ?? { width, height }, { width, height })
}

/**
 * Координаты события в долях ОБЛАСТИ ЗАПИСИ; за края не выходим.
 *
 * Обратная подгонка: из CSS-пикселя текущей области вычитается поле и
 * делится на вписанный размер. Пока подпись не начата, поле нулевое и
 * размеры совпадают — то есть для обычного случая это прежняя формула.
 */
export function toPoint(
  element: HTMLCanvasElement,
  event: PointerEvent,
  box: FitBox,
): Point | null {
  const rect = element.getBoundingClientRect()
  if (rect.width === 0 || rect.height === 0) return null

  return {
    x: clamp01((event.clientX - rect.left - box.offsetX) / box.width),
    y: clamp01((event.clientY - rect.top - box.offsetY) / box.height),
  }
}

/**
 * Дребезг ли это — то есть ближе ли новая точка к предыдущей, чем MIN_STEP.
 *
 * Расстояние считается в CSS-пикселях по вписанному размеру, а не по всей
 * области: доли относятся к области записи, и порог в пикселях иначе поехал бы.
 */
export function isTooClose(from: Point, to: Point, box: FitBox): boolean {
  const dx = (to.x - from.x) * box.width
  const dy = (to.y - from.y) * box.height
  return Math.hypot(dx, dy) < MIN_STEP
}
