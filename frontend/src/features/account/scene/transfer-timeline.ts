/** Одна монета: кадры входа и выхода на каждом из двух отрезков дуги. */
export interface CoinTiming {
  /** Старт первого отрезка (вылет из карты). */
  a: number
  /** Конец первого отрезка (попадание в хаб). */
  b: number
  /** Старт второго отрезка (вылет из хаба). */
  c: number
  /** Конец второго отрезка (посадка в кошелёк). */
  d: number
}

/**
 * Кадры трёх монет, посчитанные один раз при загрузке модуля.
 *
 * Кортеж фиксированной длины, а не массив: с noUncheckedIndexedAccess обращение
 * COINS[2] к обычному массиву даёт CoinTiming | undefined, и большой финальный
 * импульс (он привязан именно к третьей монете) пришлось бы обкладывать
 * проверками на каждом кадре.
 */
export const COINS: readonly [CoinTiming, CoinTiming, CoinTiming] = [0, 1, 2].map((i) => {
  const start = T.cStart[i] ?? 0
  return {
    a: start,
    b: start + T.leg1,
    c: start + T.leg1 + T.gap,
    d: start + T.leg1 + T.gap + T.leg2,
  }
}) as [CoinTiming, CoinTiming, CoinTiming]

